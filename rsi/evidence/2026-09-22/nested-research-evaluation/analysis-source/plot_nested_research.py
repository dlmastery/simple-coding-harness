"""Plot checked native scores; measured data only, no generated illustration."""
import argparse
from pathlib import Path
import shutil

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.ticker import MaxNLocator
import pandas as pd

from run_nested_research import ARMS, workspace


def plot(phase):
    work = workspace(phase)
    checks = pd.read_csv(work / "FINAL-CHECKS.csv")
    if checks.empty or not checks.passed.all():
        raise ValueError("Checked final predictions required")
    if (work / "native-scores.png").exists():
        raise ValueError("Preserve an existing plot before revising it")
    scores = pd.read_csv(work / "NATIVE-SCORES.csv").set_index("task")
    labels = {"fixed": "Fixed portfolio", "random": "Random search", "parent": "Parent researcher",
              "i0": "Generated by I0", "i1": "Generated by I1"}
    colors = {"fixed": "#233F63", "random": "#8895A7", "parent": "#416DA6", "i0": "#BC7C22", "i1": "#00877E"}
    names = {6: "Letter recognition", 23: "Contraceptive method choice", 31: "German credit",
             361235: "Airfoil noise", 361237: "Concrete strength", 361247: "Naval simulator",
             43: "Email classification", 45: "DNA splice windows", 2074: "Satellite pixels",
             361241: "Protein decoy RMSD", 361251: "Grid stability", 361260: "Miami sale price"}
    plt.rcParams.update({"font.family": "DejaVu Sans", "font.size": 11, "axes.edgecolor": "#C4CFDA",
                         "text.color": "#172D47", "axes.labelcolor": "#172D47", "xtick.color": "#516273", "ytick.color": "#172D47"})
    figure, axes = plt.subplots(3, 2, figsize=(14, 11.2), facecolor="white")
    arms = ARMS[phase]
    for axis, (task, row) in zip(axes.flat, scores.iterrows()):
        values = [float(row[arm]) for arm in arms]
        classification = row.metric == "balanced_accuracy"
        maximum = 1 if classification else max(values)
        maximum = max(maximum, 1e-12)
        axis.set_xlim(0, maximum*1.35)
        axis.set_ylim(len(arms)-.4, -.6)
        axis.set_yticks(range(len(arms)), [labels[arm] for arm in arms])
        axis.tick_params(axis="y", length=0, pad=9)
        axis.set_title(names[int(task)], loc="left", fontsize=14, fontweight="bold", pad=15)
        axis.set_xlabel("Balanced accuracy · higher is better" if classification else "MAE · lower is better", fontsize=10)
        axis.xaxis.set_major_locator(MaxNLocator(4))
        if classification:
            axis.set_xticks([0, .25, .5, .75, 1])
        axis.grid(axis="x", color="#E8EDF2", linewidth=.8)
        axis.set_axisbelow(True)
        for side in ("top", "right", "left"):
            axis.spines[side].set_visible(False)
        for position, (arm, value) in enumerate(zip(arms, values)):
            axis.hlines(position, 0, value, color=colors[arm], alpha=.18, linewidth=2)
            axis.scatter([value], [position], s=65, color=colors[arm], zorder=3)
            number = f"{value:,.2f}" if maximum >= 1000 else f"{value:.6f}"
            axis.text(maximum*1.32, position, number, ha="right", va="center", fontsize=10, color=colors[arm])
    scope = "EXPOSED DEVELOPMENT TASKS" if phase == "development" else "RESERVED PUBLIC TASKS"
    figure.suptitle("What did the generated researchers achieve?", x=.06, y=.976, ha="left", fontsize=24, fontweight="bold")
    figure.text(.06, .936, scope + "  ·  Separate evaluation rows  ·  Actual model predictions", fontsize=12, color="#516273")
    figure.subplots_adjust(left=.20, right=.98, top=.866, bottom=.12, hspace=.65, wspace=.78)
    figure.text(.06, .055, "Every procedure receives twelve search attempts per task. One selected model is refitted and scored.", fontsize=11)
    figure.text(.06, .028, "Native units differ across tasks. Read paired uncertainty and all development costs in REPORT.md; these dots alone do not establish RSI.", fontsize=10, color="#516273")
    figure.savefig(work / "native-scores.png", dpi=160, facecolor="white")
    figure.savefig(work / "native-scores.svg", facecolor="white")
    plt.close(figure)
    shutil.copyfile(Path(__file__), work / "analysis-source" / Path(__file__).name)
    print("Wrote measured PNG and SVG; inspect both layout and numbers before publishing")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("phase", choices=list(ARMS))
    plot(parser.parse_args().phase)
